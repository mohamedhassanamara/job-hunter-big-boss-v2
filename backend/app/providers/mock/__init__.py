def _seed(*parts: str) -> int:
    return int(hashlib.sha256("|".join(parts).encode()).hexdigest()[:8], 16)


class MockJobSource:
    """Returns a couple of fresh-looking fixture jobs per call (unique ids per run)."""

    _TEMPLATES = [
        ("Data Engineer, Streaming", "Lumen Mobility", "Barcelona, Spain", "ES", RemoteType.hybrid),
        ("AI Engineer, Retrieval", "Parcela Labs", "Lisbon, Portugal", "PT", RemoteType.remote),
        ("Analytics Engineer", "Cobalto Retail", "Milan, Italy", "IT", RemoteType.onsite),
    ]

    def __init__(self, source: Source):
        self.source = source

    def fetch(self, profile: ProfileSpec) -> list[RawJob]:
        now = datetime.now(UTC)
        stamp = now.strftime("%Y%m%d%H%M%S")
        pick = self._TEMPLATES[_seed(self.source, stamp) % len(self._TEMPLATES)]
        title, company, location, country, remote = pick
        return [
            RawJob(
                source=self.source,
                external_id=f"mock-{self.source}-{stamp}",
                url=f"https://example.com/{self.source}/jobs/{stamp}",
                title=title,
                company=company,
                location=location,
                country=country,
                remote_type=remote,
                description=f"{title} at {company}. (Mock listing generated by MockJobSource.)",
                posted_at=now - timedelta(hours=3),
            )
        ]


class MockFitScorer:
    model = "mock-scorer"

    def score(self, job: JobSnapshot, experience: list[ExperienceSnapshot]) -> FitResult:
        tags = {t.lower() for e in experience for t in e.tags}
        text = f"{job.title} {job.description}".lower()
        hits = sorted(t for t in tags if t in text)
        base = 45 + (_seed(job.title, job.company) % 30)
        score = min(97, base + 4 * len(hits))
        strengths = [f"Hands-on {t} experience matches the listing" for t in hits[:3]] or [
            "Core data engineering background is relevant"
        ]
        gaps = ["No explicit mention of the team's primary cloud"] if score < 80 else []
        return FitResult(
            score=score,
            strengths=strengths,
            gaps=gaps,
            summary=f"{'Strong' if score >= 80 else 'Partial'} match for {job.title}.",
            model=self.model,
        )


class MockCVGenerator:
    model = "mock-cv"

    def generate(self, job: JobSnapshot, experience: list[ExperienceSnapshot]) -> CVContent:
        jobs = [e for e in experience if e.kind == "job"]
        projects = [e for e in experience if e.kind == "project"]
        skills = [e for e in experience if e.kind == "skill"]
        edu = [e for e in experience if e.kind in ("education", "certification")]
        return CVContent(
            name="Your Name",
            headline=f"{job.title.split('(')[0].strip()} · Data platforms & applied AI",
            contact=["Madrid, Spain", "hello@example.com", "linkedin.com/in/example"],
            summary=(
                "Senior data engineer with 7+ years building batch and streaming platforms on "
                "AWS and GCP, and the last two shipping LLM-powered features to production. "
                "I own systems end to end, from ingestion and modelling to evaluation and cost, "
                f"and I care about clear data contracts. Keen to bring this to {job.company}."
            ),
            experience=[
                CVEntry(title=e.title, org=e.org or "", dates=e.dates or "", bullets=e.bullets[:5])
                for e in jobs[:3]
            ],
            projects=[
                CVEntry(title=e.title, org=e.org or "", bullets=e.bullets[:2]) for e in projects[:3]
            ],
            skills=[CVSkillGroup(group=e.title, items=e.tags[:8]) for e in skills[:4]],
            education=[
                CVEntry(title=e.title, org=e.org or "", dates=e.dates or "", bullets=e.bullets[:1])
                for e in edu
            ],
        )


class MockCVRenderer:
    def render(self, content: CVContent, out_name: str) -> RenderedCV:
        tex = f"% mock render of {out_name}\n\\documentclass{{article}}\n% {content.headline}\n"
        return RenderedCV(tex=tex, pdf_path=None, page_count=1)


