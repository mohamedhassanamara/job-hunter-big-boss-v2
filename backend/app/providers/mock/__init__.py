def _seed(*parts: str) -> int:
    return int(hashlib.sha256("|".join(parts).encode()).hexdigest()[:8], 16)


class MockJobSource:
    """Returns a couple of fresh-looking fixture jobs per call (unique ids per run)."""

    _TEMPLATES = [
        ("Data Engineer, Streaming", "Lumen Mobility", "Barcelona, Spain", "ES", RemoteType.hybrid),
        ("AI Engineer, Retrieval", "Parcela Labs", "Lisbon, Portugal", "PT", RemoteType.remote),
        ("Analytics Engineer", "Cobalto Retail", "Milan, Italy", "IT", RemoteType.onsite),
    ]

    cooldown_hours = 0.0

    def __init__(self, source: Source):
        self.source = source
        self.requests = 0

    def configured(self) -> str | None:
        return None

    def fetch(self, profile: ProfileSpec) -> list[RawJob]:
        self.requests = 1
        now = datetime.now(UTC)
        stamp = now.strftime("%Y%m%d%H%M%S")
        pick = self._TEMPLATES[_seed(self.source, stamp) % len(self._TEMPLATES)]
        title, company, location, country, remote = pick
        return [
            RawJob(
                source=self.source,
                external_id=f"mock-{self.source}-{stamp}",
                url=f"https://example.com/{self.source}/jobs/{stamp}",
                title=title,
                company=company,
                location=location,
                country=country,
                remote_type=remote,
                description=f"{title} at {company}. (Mock listing generated by MockJobSource.)",
                posted_at=now - timedelta(hours=3),
            )
        ]


class MockFitScorer:
    """Deterministic stand-in for the LLM (sandbox, tests). Evidence quotes are taken from the
    job text so they verify like real ones."""

    model = "mock-scorer"

    def assess(self, system: str, user: str, job: JobSnapshot) -> FitAssessment:
        seed = _seed(job.title, job.company)
        text = job.description or job.title
        quote = " ".join(text.split()[:8])
        title = job.title.lower()
        role = 9 if any(w in title for w in ("data", "ml", "ai", "analytics", "machine")) else 3
        senior = 3 if any(w in title for w in ("staff", "principal", "head", "lead")) else 8
        location = 9 if job.remote_type == "remote" else 6

        def sub(score: int, reason: str) -> SubScore:
            return SubScore(score=score, reason=reason, evidence=quote)

        return FitAssessment(
            role_match=sub(role, "Title and responsibilities match a target role."),
            skills_match=sub(4 + seed % 6, "Some overlap with the listed stack."),
            seniority_fit=sub(senior, "Level inferred from the title."),
            location_eligibility=sub(location, "Work mode versus your targets."),
            language_requirements=sub(8, "No language requirement stated."),
            red_flags=[],
            strengths=["Relevant data engineering background"],
            gaps=["Cloud provider differs"] if seed % 2 else [],
            summary=f"{'Strong' if role > 6 else 'Weak'} match for {job.title}.",
        )


class MockCVGenerator:
    """Deterministic plan from the pool: relevance = keyword overlap with the job text, facts
    kept in their original wording and order. Used by tests and the tour sandbox."""

    model = "mock-cv"
    prompt_version = "cv_generate/mock"

    def generate(self, request: CVRequest) -> CVPlan:
        pool, job = request.pool, request.job
        words = {w for w in re.findall(r"[a-z0-9+#]+", " ".join(
            str(job.get(k) or "") for k in ("title", "description", "matched_track")).lower())
            if len(w) > 2}

        def relevance(entry: dict) -> int:
            text = " ".join([entry.get("title") or "", *entry.get("tags", []),
                             *entry.get("facts", {}).values()]).lower()
            hits = sum(1 for w in words if w in text)
            return max(1, min(10, 3 + hits))

        def entry(e: dict) -> dict:
            return {"item_id": e["id"], "relevance": relevance(e), "bullets": [
                {"source_index": int(k), "text": v, "priority": n + 1}
                for n, (k, v) in enumerate(e.get("facts", {}).items())]}

        sentences = self._sentences(pool)
        projects = sorted(pool.get("projects", []), key=relevance, reverse=True)
        return plan_from_draft(CVPlanDraft(
            summary_sentences=sentences,
            summary_short_sentences=sentences[:1],
            skills=[{"item_id": g["id"], "items": g["skills"]}
                    for g in pool.get("skill_groups", [])],
            roles=[entry(r) for r in pool.get("roles", [])],
            projects=[{**entry(p), "stack": p.get("tags", [])[:6]} for p in projects],
            certification_ids=[c["id"] for c in pool.get("certifications", [])],
            education_ids=[e["id"] for e in pool.get("education", [])],
        ))

    @staticmethod
    def _sentences(pool: dict) -> list[SummarySentence]:
        """A snippet verbatim when there is one, else the first facts of the latest roles; each
        sentence cites its source, so the grounding check passes."""
        snippets = pool.get("summary_snippets") or []
        if snippets:
            return [SummarySentence(text=snippets[0]["text"], citations=[snippets[0]["id"]])]
        out = []
        for role in pool.get("roles", [])[:2]:
            fact = next(iter(role.get("facts", {}).values()), "")
            if fact:
                out.append(SummarySentence(text=fact.rstrip(".") + ".", citations=[role["id"]]))
        return out

    def generate_summary(self, request: CVRequest, feedback: str) -> SummaryDraft:
        sentences = self._sentences(request.pool)
        return SummaryDraft(summary_sentences=sentences, summary_short_sentences=sentences[:1])


class MockEmailDrafter:
    """A short, grounded draft built from the request (sandbox and tests; no model call)."""

    model = "mock-drafter"
    prompt_version = "outreach/mock"

    def draft(self, request: EmailRequest, feedback: str = "") -> EmailDraftPlan:
        job, contact = request.job, request.contact
        role = next((r for r in request.pool.get("roles", []) if r.get("facts")), None)
        sentences = [EmailSentence(
            text=f"I saw that {job.get('company')} is hiring for the {job.get('title')} role.",
            about_job=True)]
        if role:
            fact = next(iter(role["facts"].values()))
            sentences.append(EmailSentence(
                text=f"At {role.get('org')}, I {fact[0].lower()}{fact[1:].rstrip('.')}.",
                citations=[role["id"]]))
        return EmailDraftPlan(
            subject=f"{job.get('title')} at {job.get('company')}"[:80],
            greeting=f"Hi {contact.get('first_name')},",
            sentences=sentences,
            ask="Would you be open to a 15-minute call next week?",
        )

    @staticmethod
    def sample(title: str, company: str, first_name: str) -> tuple[str, str]:
        """Static sample text for the tour sandbox's seeded drafts."""
        return (f"{title} at {company}", (
            f"Hi {first_name},\n\nI saw that {company} is hiring for the {title} role. At my "
            "last company I built batch and streaming data pipelines on Spark and Airflow.\n\n"
            "Would you be open to a 15-minute call next week?"))


class MockLetterDrafter:
    """A grounded cover letter and answers built from the request's pool (sandbox and tests; no
    model call): pool facts quoted with their citations, the listing only for the opening."""

    model = "mock-letter"
    prompt_version = "cover_letter/mock"

    @staticmethod
    def _facts(pool: dict, limit: int = 3) -> list[tuple[int, str, str]]:
        items = [i for k in ("roles", "projects") for i in pool.get(k, []) if i.get("facts")]
        return [(i["id"], i.get("org") or i.get("title") or "", f.rstrip("."))
                for i in items[:limit] for f in i["facts"].values()]

    def draft_letter(self, request: LetterRequest, feedback: str = "") -> CoverLetterPlan:
        job, fr = request.job, request.rules.get("language") == "fr"
        company, title = job.get("company"), job.get("title")
        opening = (f"{company} recrute pour le poste de {title}." if fr
                   else f"{company} is hiring for the {title} role.")
        min_words = int(request.rules.get("min_words") or 250)
        facts = self._facts(request.pool)
        middle: list[list[EmailSentence]] = [[], []]
        words = len(opening.split())
        for n, (item_id, org, fact) in enumerate(facts):
            lead = f"Chez {org}, voici ce que j'ai fait : " if fr else f"At {org}, "
            text = f"{lead}{fact[0].lower()}{fact[1:]}." if not fr else f"{lead}{fact}."
            middle[n % 2].append(EmailSentence(text=text, citations=[item_id]))
            words += len(text.split())
            if words >= min_words:
                break
        first = facts[0][0] if facts else 0
        close = EmailSentence(text=("Mon CV joint détaille ces expériences." if fr
                                    else "My CV has the details of this work."),
                              citations=[first])
        paragraphs = [LetterParagraph(sentences=[EmailSentence(text=opening, about_job=True)])]
        paragraphs += [LetterParagraph(sentences=p) for p in middle if p]
        paragraphs.append(LetterParagraph(sentences=[close]))
        ask = (f"Seriez-vous disponible pour un entretien au sujet du poste de {title} ?" if fr
               else f"Would you be open to an interview about the {title} role?")
        return CoverLetterPlan(paragraphs=paragraphs, ask=ask)

    def answer(self, request: AnswersRequest, feedback: str = "") -> AnswersPlan:
        facts = self._facts(request.pool, limit=1)
        out = []
        for q in request.questions:
            item_id, org, fact = facts[0] if facts else (0, "", "")
            text = f"At {org}, {fact[0].lower()}{fact[1:]}." if fact else "I will confirm this."
            limit = q.get("char_limit")
            if limit and len(text) > limit:
                text = f"At {org}, I built this."[:limit] if org else text[:limit]
            out.append(AnswerDraft(question_id=int(q["id"]),
                                   sentences=[EmailSentence(text=text, citations=[item_id])]))
        return AnswersPlan(answers=out)


class MockMailer:
    """Never sends anything. Records calls for tests (and can be told to fail)."""

    def __init__(self) -> None:
        self.sent: list[OutgoingEmail] = []
        self.fail: SendFailed | None = None

    def send(self, email: OutgoingEmail) -> str:
        if self.fail is not None:
            raise self.fail
        self.sent.append(email)
        return f"<mock-{len(self.sent)}@job-hunter.local>"
