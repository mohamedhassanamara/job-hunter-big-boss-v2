def _seed(*parts: str) -> int:
    return int(hashlib.sha256("|".join(parts).encode()).hexdigest()[:8], 16)


class MockJobSource:
    """Returns a couple of fresh-looking fixture jobs per call (unique ids per run)."""

    _TEMPLATES = [
        ("Data Engineer, Streaming", "Lumen Mobility", "Barcelona, Spain", "ES", RemoteType.hybrid),
        ("AI Engineer, Retrieval", "Parcela Labs", "Lisbon, Portugal", "PT", RemoteType.remote),
        ("Analytics Engineer", "Cobalto Retail", "Milan, Italy", "IT", RemoteType.onsite),
    ]

    cooldown_hours = 0.0

    def __init__(self, source: Source):
        self.source = source
        self.requests = 0

    def configured(self) -> str | None:
        return None

    def fetch(self, profile: ProfileSpec) -> list[RawJob]:
        self.requests = 1
        now = datetime.now(UTC)
        stamp = now.strftime("%Y%m%d%H%M%S")
        pick = self._TEMPLATES[_seed(self.source, stamp) % len(self._TEMPLATES)]
        title, company, location, country, remote = pick
        return [
            RawJob(
                source=self.source,
                external_id=f"mock-{self.source}-{stamp}",
                url=f"https://example.com/{self.source}/jobs/{stamp}",
                title=title,
                company=company,
                location=location,
                country=country,
                remote_type=remote,
                description=f"{title} at {company}. (Mock listing generated by MockJobSource.)",
                posted_at=now - timedelta(hours=3),
            )
        ]


class MockFitScorer:
    """Deterministic stand-in for the LLM (sandbox, tests). Evidence quotes are taken from the
    job text so they verify like real ones."""

    model = "mock-scorer"

    def assess(self, system: str, user: str, job: JobSnapshot) -> FitAssessment:
        seed = _seed(job.title, job.company)
        text = job.description or job.title
        quote = " ".join(text.split()[:8])
        title = job.title.lower()
        role = 9 if any(w in title for w in ("data", "ml", "ai", "analytics", "machine")) else 3
        senior = 3 if any(w in title for w in ("staff", "principal", "head", "lead")) else 8
        location = 9 if job.remote_type == "remote" else 6

        def sub(score: int, reason: str) -> SubScore:
            return SubScore(score=score, reason=reason, evidence=quote)

        return FitAssessment(
            role_match=sub(role, "Title and responsibilities match a target role."),
            skills_match=sub(4 + seed % 6, "Some overlap with the listed stack."),
            seniority_fit=sub(senior, "Level inferred from the title."),
            location_eligibility=sub(location, "Work mode versus your targets."),
            language_requirements=sub(8, "No language requirement stated."),
            red_flags=[],
            strengths=["Relevant data engineering background"],
            gaps=["Cloud provider differs"] if seed % 2 else [],
            summary=f"{'Strong' if role > 6 else 'Weak'} match for {job.title}.",
        )


class MockCVGenerator:
    """Deterministic plan from the pool: relevance = keyword overlap with the job text, facts
    kept in their original wording and order. Used by tests and the tour sandbox."""

    model = "mock-cv"
    prompt_version = "cv_generate/mock"

    def generate(self, request: CVRequest) -> CVPlan:
        pool, job = request.pool, request.job
        words = {w for w in re.findall(r"[a-z0-9+#]+", " ".join(
            str(job.get(k) or "") for k in ("title", "description", "matched_track")).lower())
            if len(w) > 2}

        def relevance(entry: dict) -> int:
            text = " ".join([entry.get("title") or "", *entry.get("tags", []),
                             *entry.get("facts", {}).values()]).lower()
            hits = sum(1 for w in words if w in text)
            return max(1, min(10, 3 + hits))

        def entry(e: dict) -> dict:
            return {"item_id": e["id"], "relevance": relevance(e), "bullets": [
                {"source_index": int(k), "text": v, "priority": n + 1}
                for n, (k, v) in enumerate(e.get("facts", {}).items())]}

        snippets = pool.get("summary_snippets") or []
        summary = snippets[0]["text"] if snippets else " ".join(
            r["title"] + (f" at {r['org']}" if r.get("org") else "") + "."
            for r in pool.get("roles", [])[:2])
        projects = sorted(pool.get("projects", []), key=relevance, reverse=True)
        return CVPlan(
            summary=summary,
            summary_short=summary.split(". ")[0].rstrip(".") + ".",
            summary_source_ids=[snippets[0]["id"]] if snippets else [],
            skills=[{"item_id": g["id"], "items": g["skills"]}
                    for g in pool.get("skill_groups", [])],
            roles=[entry(r) for r in pool.get("roles", [])],
            projects=[{**entry(p), "stack": p.get("tags", [])[:6]} for p in projects],
            certification_ids=[c["id"] for c in pool.get("certifications", [])],
            education_ids=[e["id"] for e in pool.get("education", [])],
        )


class MockEmailDrafter:
    model = "mock-drafter"

    def draft(
        self, job: JobSnapshot, contact: ContactSnapshot, cv: dict | None
    ) -> DraftResult:
        first = contact.full_name.split()[0]
        return DraftResult(
            subject=f"{job.title} at {job.company}: data engineer with LLM platform experience",
            body=(
                f"Hi {first},\n\n"
                f"I saw {job.company} is hiring a {job.title} and wanted to reach out directly. "
                "I've spent the last few years building batch and streaming data platforms "
                "(Spark, dbt, Airflow) and, more recently, retrieval pipelines for LLM "
                "features.\n\n"
                "A couple of things that seem relevant to the role:\n"
                "- Cut warehouse costs ~35% by re-modelling core pipelines in dbt\n"
                "- Shipped a RAG service used by 2k internal users\n\n"
                "I've attached a one-page CV. Would you be open to a short call next week?\n\n"
                "Best,\nYour Name"
            ),
            model=self.model,
        )


